// Generates en/index.html from the Portuguese index.html and the locale files.
// Run by hand after editing index.html or a locale file:  node scripts/i18n-pages.mjs [outDir]
// With no outDir the file is written into the repository. No bundler: plain string replacement over our own markup.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const SITE = 'https://demo.alphatester.app/';
const PREFIX = { 'pt-BR': '', en: 'en/' };

const dict = (loc) => JSON.parse(readFileSync(`${root}assets/i18n/${loc}.json`, 'utf8'));
const get = (d, key) => key.split('.').reduce((v, k) => (v == null ? v : v[k]), d);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escAttr = (s) => esc(s).replace(/"/g, '&quot;');

function value(d, key) {
  const v = get(d, key);
  if (typeof v !== 'string') throw new Error(`missing key ${key}`);
  return v;
}

export function localize(src, loc) {
  const d = dict(loc);
  let out = src;
  // elements whose content is plain text
  out = out.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)([^<]*)(<\/\2>)/g,
    (m, open, tag, key, _t, close) => open + esc(value(d, key)) + close);
  // elements whose content is trusted markup from our own locale files
  out = out.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n-html="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/g,
    (m, open, tag, key, _t, close) => open + value(d, key) + close);
  // attributes: data-i18n-attr="attr:key;attr:key"
  out = out.replace(/<[a-z][^>]*\sdata-i18n-attr="([^"]+)"[^>]*>/g, (tag, spec) => {
    for (const pair of spec.split(';')) {
      const [attr, key] = pair.split(':').map((x) => x.trim());
      tag = tag.replace(new RegExp(`(\\s${attr}=")[^"]*(")`), `$1${escAttr(value(d, key))}$2`);
    }
    return tag;
  });
  // canonical URL of this locale's page
  out = out.replace(/<link rel="canonical"[^>]*>/, `<link rel="canonical" href="${SITE}${PREFIX[loc]}" data-canonical="">`);
  // language switch: mark the current locale
  out = out.replace(/<a href="([^"]*)"([^>]*)data-lang-link="([^"]+)"[^>]*>/g,
    (tag, href, mid, l) => `<a href="${href}"${mid}data-lang-link="${l}"${l === loc ? ' aria-current="page"' : ''}>`);
  if (loc !== 'pt-BR') {
    out = out.replace('<html lang="pt-BR">', `<html lang="${loc}">`);
    out = out.replace('<head>\n', '<head>\n  <!-- generated by scripts/i18n-pages.mjs from index.html; edit index.html or the locale files and rerun -->\n');
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outDir = process.argv[2] ? process.argv[2].replace(/\/?$/, '/') : root;
  const target = `${outDir}en/index.html`;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, localize(readFileSync(`${root}index.html`, 'utf8'), 'en'));
  console.log('wrote en/index.html');
}
